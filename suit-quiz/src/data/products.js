function tier(id, name, plain, icon, detail, alterationIds) {
  const items = alterationIds.map((key) => ({ id: key, ...ALTERATIONS[key] }));
  return { id, name, plain, icon, detail, items, price: items.reduce((sum, item) => sum + item.price, 0) };
}

