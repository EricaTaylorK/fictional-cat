function suit(overrides) {
  const product = {
    promos: [],
    occasions: ["business"],
    jacket: "single",
    lining: "full",
    lapel: "notch",
    pattern: "solid",
    type: "2-piece",
    compareAt: null,
    ...overrides,
  };
  const chests = product.sizes ?? [];
  product.sizes =
    import.meta.env.VITE_SIZE_VARIANT === "lite"
      ? sizesForChests(chests)
      : expandSuitSizes(chests, product.id);
  return product;
}

